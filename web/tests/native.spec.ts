import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const url = process.env.CODEXM_WEB_TEST_URL || "http://127.0.0.1:14317";
const state = process.env.CODEXM_WEB_TEST_STATE;
test.skip(!state, "isolated native-CLI web fixture required");
test("compact chat selection, native terminal, literal input and persisted CLI", async ({ page }) => {
  await page.goto(url);
  const denied = await page.evaluate(() => new Promise(resolve => (window as any).Meteor.call("codexm.call", "terminal.open", { thread_id: "invalid", account: "default" }, "operation-fixture-1234", (error: any) => resolve(error?.error))));
  expect(denied).toBe("authentication_required");
  await page.getByLabel("로컬 접속 코드").fill(readFileSync(state + "/access", "utf8").trim());
  await page.getByRole("button", { name: "연결", exact: true }).click();
  await page.getByRole("button", { name: /한글 프로젝트 계획/ }).click();
  await expect(page.getByRole("button", { name: "Codex CLI로 이어가기" })).toBeDisabled();
  await page.getByLabel("이번에 사용할 계정").selectOption("alpha");
  await page.getByRole("button", { name: "Codex CLI로 이어가기" }).click();
  const terminal = page.getByRole("log");
  await expect(terminal).toContainText("Selected account: alpha", { timeout: 20000 });
  const input = page.getByLabel("CLI에 전달할 입력");
  await input.fill("한글 확인");
  await input.dispatchEvent("keydown", { key: "Enter", keyCode: 229, isComposing: true });
  await expect(input).toHaveValue("한글 확인");
  await page.getByRole("button", { name: "CLI에 전달", exact: true }).click();
  await expect(terminal).toContainText("Received: 한글 확인");
  const literal = 'literal $(printf should-not-execute) ; & <test>';
  await input.fill(literal); await page.getByRole("button", { name: "CLI에 전달", exact: true }).click();
  await expect(terminal).toContainText("Received: " + literal);
  await page.screenshot({ path: process.env.CODEXM_WEB_SCREENSHOT || "/tmp/codexm-native-web.png", fullPage: true });
  await page.reload();
  await page.getByRole("button", { name: /한글 프로젝트 계획/ }).click();
  await page.getByLabel("이번에 사용할 계정").selectOption("alpha");
  await page.getByRole("button", { name: "Codex CLI로 이어가기" }).click();
  await expect(terminal).toContainText("Received: 한글 확인");
  await page.getByLabel("보관된 채팅 포함").check();
  await expect(page.getByRole("button", { name: /보관된 작업 기록/ })).toBeVisible();
  await page.getByRole("button", { name: "계정", exact: true }).click();
  await expect(page.getByRole("heading", { name: "계정", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "관리자", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "채팅", exact: true }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "터미널 종료", exact: true }).click();
  await expect(terminal).toHaveCount(0);
  // Retained receipts for a closed terminal must allow a fresh native CLI.
  await page.getByRole("button", { name: "Codex CLI로 이어가기" }).click();
  await expect(terminal).toContainText("Selected account: alpha", { timeout: 20000 });
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "터미널 종료", exact: true }).click();
  await expect(terminal).toHaveCount(0);
});
