// Regenerate the browser capability types after changing the Go API surface.
package main

import (
	"encoding/json"
	"fmt"
	"github.com/codeasy-digix/codexm/internal/application"
	"os"
)

func main() {
	document := map[string]any{"protocolVersion": application.ProtocolVersion, "methods": application.Methods()}
	b, err := json.MarshalIndent(document, "", "  ")
	if err == nil {
		err = os.MkdirAll("contracts", 0755)
	}
	if err == nil {
		err = os.WriteFile("contracts/methods-v1.json", append(b, '\n'), 0644)
	}
	if err == nil {
		err = os.WriteFile("web/imports/contracts/generated.ts", []byte("// Generated by go run ./cmd/webcontract.\nexport const bridgeContract = "+string(b)+" as const;\nexport type MethodName = (typeof bridgeContract.methods)[number]['name'];\n"), 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
